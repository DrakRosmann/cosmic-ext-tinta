//! Interface text. English is the key; Brazilian Portuguese is looked up when the locale asks.

use std::sync::OnceLock;

pub fn is_portuguese() -> bool {
    static PT: OnceLock<bool> = OnceLock::new();
    *PT.get_or_init(|| {
        let forced = tinta_core::settings::Settings::load().0.language;
        if !forced.is_empty() {
            return forced.starts_with("pt");
        }
        ["LC_ALL", "LC_MESSAGES", "LANG"]
            .iter()
            .filter_map(|v| std::env::var(v).ok())
            .find(|v| !v.is_empty())
            .is_some_and(|v| v.starts_with("pt"))
    })
}

